#!/usr/bin/env node
// Regenerates shared/vendor/yaml.js: the `yaml` package bundled into one file.
// Why vendored: the Paseo daemon compiles plugins itself and only provides the plugin SDK and zod; any other
// dependency must ship inside the plugin. A committed bundle means installing the plugin needs no npm and no network.
//   npm run vendor:yaml
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "node_modules/yaml/package.json"), "utf8"));
const out = path.join(root, "shared/vendor");
fs.mkdirSync(out, { recursive: true });

const entry = 'export { parse, parseDocument, stringify } from "yaml";\n';
const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: "js" },
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2020",
  minify: true,
  legalComments: "none",
  write: false,
});
const banner = `// Vendored: yaml@${pkg.version} (ISC, see yaml.LICENSE). Generated by scripts/vendor-yaml.mjs; do not edit.\n`;
fs.writeFileSync(path.join(out, "yaml.js"), banner + result.outputFiles[0].text);
fs.copyFileSync(path.join(root, "node_modules/yaml/LICENSE"), path.join(out, "yaml.LICENSE"));
console.log(`vendored yaml@${pkg.version} (${result.outputFiles[0].text.length} bytes)`);
